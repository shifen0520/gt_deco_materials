    /**
     * 木质方块名集合（用户要求「树苗继承橡木树苗类，木头、树叶也一样跟着」）。
     *
     * <p>直接复用原版方块类，免费拿到全套配套行为：
     * <ul>
     *   <li>{@code *_log} → {@link net.minecraft.world.level.block.RotatedPillarBlock}：
     *       带 {@code axis} 属性，可竖放/横放、模型随之切换。</li>
     *   <li>{@code *_leaves} → {@link net.minecraft.world.level.block.LeavesBlock}：
     *       带 {@code distance/persistent/waterlogged}，支持正确衰减与含水、可剪可催发。</li>
     *   <li>{@code *_sapling} → {@link net.minecraft.world.level.block.SaplingBlock}：
     *       带 {@code stage} 与骨粉催熟，碰撞形状是细杆而非整方块。</li>
     * </ul>
     */
    private static boolean isLog(String name) {
        return name.endsWith("_log");
    }

    private static boolean isLeaves(String name) {
        return name.endsWith("_leaves");
    }

    private static boolean isSapling(String name) {
        return name.endsWith("_sapling");
    }

    public static void register() {
        if (CASINGS.length == 0) {
            GTDecoration.LOGGER.warn("No casing blocks to register.");
            return;
        }
        int count = 0;
        for (String name : CASINGS) {
            // 玻璃类方块用半透明 GlassBlock，其余用普通方块。
            // Minecraft 的模型 json 无法表达 alpha 混合，透明必须由方块类型声明。
            boolean glass = Casings.GLASS.contains(name);
            var builder = glass
                    ? GTDecoration.REGISTRY.block(name, GlassBlock::new)
                    : "rubber_log".equals(name)
                        ? GTDecoration.REGISTRY.block(name, ResinLogBlock::new)
                        : isLog(name)
                        ? GTDecoration.REGISTRY.block(name,
                                net.minecraft.world.level.block.RotatedPillarBlock::new)
                        : isLeaves(name)
                            ? GTDecoration.REGISTRY.block(name,
                                    net.minecraft.world.level.block.LeavesBlock::new)
                            : isSapling(name)
                                ? GTDecoration.REGISTRY.block(name,
                                        (java.util.function.Function<
                                                net.minecraft.world.level.block.state.BlockBehaviour.Properties,
                                                Block>)
                                                p -> new net.minecraft.world.level.block.SaplingBlock(null, p))
                                : GTDecoration.REGISTRY.block(name, Block::new);
            builder.lang(MaterialNames.display(name));
            builder.properties(p -> p.strength(5.0F, 6.0F));
            if (glass) {
                // 玻璃的一整套行为（用户要求「声音改玻璃 / 去阴影 / 继承玻璃方块类 /
                // 不需要精准采集」）都在这里声明：
                // - noOcclusion：不遮挡相邻面，玻璃之间与玻璃和地面之间不出现黑缝
                // - sound(GLASS)：行走/破坏/放置都是玻璃音
                // - isViewBlocking(false)：不当作实心遮挡面
                // - 精准采集：Properties.requiresCorrectToolForDrops() 是「置true」的单参方法，
                //   默认值本来就是 false，所以这里**不要调用它**，玻璃即天然徒手可打、不需要精准采集。
                // 不作为红石导体。透明渲染层由 GlassRenderTypes 在客户端注册。
                // 去阴影还依赖 GlassBlock 覆写 getLightBlock(0) 与 getShadeBrightness(1.0f)。
                builder.properties(p -> p.noOcclusion()
                        .isRedstoneConductor((state, level, pos) -> false)
                        .sound(net.minecraft.world.level.block.SoundType.GLASS)
                        .isViewBlocking((state, level, pos) -> false));
            }
            boolean wood = isLog(name) || isLeaves(name) || isSapling(name)
                    || name.endsWith("_planks") || name.endsWith("_wood");
            if (wood) {
                // 木质方块（用户要求「木头、树叶也跟着继承原版」）：
                // - 声音走 WOOD，与原版木头/树叶一致
                // - strength 用木头的 2.0/3.0，不用机械外壳的 5.0/6.0
                // - noOcclusion：树叶与树苗不遮挡相邻面（LeavesBlock/SaplingBlock 自身会算形状）
                // - 树叶支持含水（LeavesBlock 实现了 SimpleWaterloggedBlock）
                builder.properties(p -> p.strength(2.0F, 3.0F)
                        .sound(net.minecraft.world.level.block.SoundType.WOOD)
                        .noOcclusion());
            }
            // blockstate 与贴图由 tools/ctm/* 脚本预生成到 src/main/resources
            // （Athena 连接纹理的 blockstate 不能被 registrylib 覆盖）。
            builder.noBlockstate();
            // 关键：方块物品模型已由 tools/ctm/* 预生成到
            // src/main/resources/assets/gt_deco_materials/models/item/<name>.json，
            // 这里用 createWithExistingModel 直接引用它们，
            // 避免 registrylib 生成引用不存在贴图的默认模型（紫黑格）。
            final ResourceLocation itemModel =
                    ResourceLocation.fromNamespaceAndPath(GTDecoration.MODID, "item/" + name);
            // 机械外壳可被镐挖；木质方块挂对应的斧/铲标签（与原版木头一致）
            builder.addTag(TagKey.create(Registries.BLOCK,
                    ResourceLocation.fromNamespaceAndPath("minecraft",
                            wood ? (isLeaves(name) || isSapling(name) ? "mineable/hoe" : "mineable/axe")
                                 : "mineable/pickaxe")));
            // 外壳通常可被同类连接纹理拼接，统一挂 c:storage_blocks 便于互推/配方引用
            builder.addTag(TagKey.create(Registries.BLOCK,
                    ResourceLocation.fromNamespaceAndPath("c", "storage_blocks")));
            builder.addTag(TagKey.create(Registries.BLOCK,
                    ResourceLocation.fromNamespaceAndPath("c", "casings")));
            builder.addTag(TagKey.create(Registries.BLOCK,
                    ResourceLocation.fromNamespaceAndPath("c", "casings/" + name)));
            // 方块物品：进 blocks 标签页 + 显式模型（一次 item() 配置全部）
            builder.item(item -> {
                item.addTab(BuiltinSHJTCreativeTabs.BLOCKS_KEY);
                item.addTag(TagKey.create(Registries.ITEM,
                        ResourceLocation.fromNamespaceAndPath("c", "casings")));
                item.addTag(TagKey.create(Registries.ITEM,
                        ResourceLocation.fromNamespaceAndPath("c", "casings/" + name)));
                item.model(() -> (i, gen) -> gen.createWithExistingModel(i, itemModel));
            }).register();
            count++;
        }
        GTDecoration.LOGGER.info("Registered {} casing blocks with Athena connected textures.", count);
    }
