    public static void register() {
        if (ITEMS.length == 0) {
            return;
        }
        int count = 0;
        for (String name : ITEMS) {
            var builder = GTDecoration.REGISTRY.item(name, Item::new);
            builder.lang(MaterialNames.display(name));
            builder.addTag(TagKey.create(Registries.ITEM,
                    ResourceLocation.fromNamespaceAndPath("c", "special_items")));
            builder.addDefaultTab();
            builder.register();
            count++;
        }
        GTDecoration.LOGGER.info("Registered {} GTO/GTM special & material items.", count);
    }
